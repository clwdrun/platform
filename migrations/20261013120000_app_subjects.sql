-- Pairwise subjects (#11): the identity an app sees for a person.
--
-- An app never sees the platform user id. Each (app, user) pair gets its own
-- subject, so two apps comparing notes cannot link a visitor by subject, and a
-- subject leaked from one app means nothing in another. (They can still link
-- by email while email is exposed; pairwise keeps the user id inside the
-- platform and keeps unlinkability possible if email is ever withheld.)
--
-- The subject is stored, not derived. App data is keyed `u.{subject}`, so a
-- subject must never change for a given app and user: across deploys, and
-- across any key rotation. An HMAC of the user id would change with its key
-- and orphan every user's data; a stored random value has no key to rotate.
-- Rows are never deleted (`on delete restrict` on both parents).
--
-- Random, UUIDv4, generated by the database. Not v7: a v7 encodes the time of
-- the first visit, which colluding apps could use to correlate visitors. The
-- check holds the version nibble, so a v7 (or anything else) cannot be
-- written here by mistake.
--
-- Written at the handshake's code exchange, `on conflict do nothing`, in the
-- same statement that issues the app-host session. Two concurrent first
-- exchanges for one (app, user) meet on the primary key and keep one subject.
--
-- ROLLBACK PLAN: none required. This migration only creates a table. Dropping
-- it would hand every user a new subject in every app, orphaning their app
-- data, so it must never be reverted once an app has stored any.

create table app_subjects (
    app_id     uuid        not null references apps (id) on delete restrict,
    user_id    uuid        not null references users (id) on delete restrict,
    subject    uuid        not null unique default gen_random_uuid()
                           check (substr(subject::text, 15, 1) = '4'),
    created_at timestamptz not null default now(),
    primary key (app_id, user_id)
);
